<?php
/**
 * Generates next/config/routes/auth.yaml.
 *
 * Two legacy mechanisms have to be unwound here:
 *
 * 1. XML routing. app/Core/UserBundle ships security.xml and user/group.xml;
 *    port-routing.php only handles YAML.
 *
 * 2. Bundle inheritance. Core\UserBundle::getParent() returns 'FOSUserBundle',
 *    so every "FOSUserBundle:Security:check" style reference actually resolved
 *    to the app's own overriding controller. Symfony 4 removed bundle
 *    inheritance, so those references are pointed straight at the app's
 *    controllers, which are already ported to App\User\Controller.
 *
 * The profile / resetting / change_password / registration route groups came
 * from FOSUserBundle's own XML, which disappears with the bundle; they are
 * re-declared here against the same overriding controllers.
 *
 * usage: php migration/bin/port-auth-routes.php
 */
$root = dirname(__DIR__, 2);
$out  = "$root/next/config/routes/auth.yaml";

/** Both prefixes resolve to the app's controllers - see bundle inheritance above. */
$ctrl = static fn (string $c, string $a): string => "App\\User\\Controller\\{$c}Controller::{$a}Action";

$routes = [];

// ---- 1. the app's own XML route files --------------------------------------
$xmlFiles = [
    "$root/src/Core/UserBundle/Resources/config/security.xml"   => '',
    "$root/src/Core/UserBundle/Resources/config/user/group.xml" => '/system-users/group',
];

foreach ($xmlFiles as $file => $prefix) {
    if (!is_file($file)) { fwrite(STDERR, "missing $file\n"); continue; }
    $xml = simplexml_load_file($file);
    if ($xml === false) { fwrite(STDERR, "unparseable $file\n"); continue; }

    foreach ($xml->route as $r) {
        $id   = (string) $r['id'];
        // SF2 allowed either attribute; "pattern" was removed in SF3.
        $path = (string) ($r['path'] ?? '') ?: (string) ($r['pattern'] ?? '');
        $methods = trim((string) ($r['methods'] ?? ''));

        $controller = null;
        foreach ($r->default as $d) {
            if ((string) $d['key'] === '_controller') $controller = trim((string) $d);
        }
        // SF2 expressed the method constraint as a requirement; SF3+ uses methods.
        foreach ($r->requirement as $req) {
            if ((string) $req['key'] === '_method' && $methods === '') $methods = trim((string) $req);
        }
        if ($controller === null) continue;

        if (!preg_match('/^[A-Za-z]+Bundle:([A-Za-z0-9_]+):([A-Za-z0-9_]+)$/', $controller, $m)) continue;

        $routes[$id] = [
            'path'       => $prefix . $path,
            'controller' => $ctrl($m[1], $m[2]),
            'methods'    => $methods === '' ? [] : preg_split('/[\s,|]+/', $methods),
        ];
    }
}

// ---- 2. route groups that lived inside FOSUserBundle ------------------------
// Paths and names copied from the locked FOSUserBundle revision's routing XML,
// with the prefixes app/config wired them under.
$fosGroups = [
    '/signup' => [
        'fos_user_registration_register'  => ['/',           'Registration', 'register',       ['GET', 'POST']],
        'fos_user_registration_check_email' => ['/check-email', 'Registration', 'checkEmail',  ['GET']],
        'fos_user_registration_confirm'   => ['/confirm/{token}', 'Registration', 'confirm',   ['GET']],
        'fos_user_registration_confirmed' => ['/confirmed',  'Registration', 'confirmed',      ['GET']],
    ],
    '/resetting' => [
        'fos_user_resetting_request'     => ['/request',      'Resetting', 'request',     ['GET']],
        'fos_user_resetting_send_email'  => ['/send-email',   'Resetting', 'sendEmail',   ['POST']],
        'fos_user_resetting_check_email' => ['/check-email',  'Resetting', 'checkEmail',  ['GET']],
        'fos_user_resetting_reset'       => ['/reset/{token}','Resetting', 'reset',       ['GET', 'POST']],
    ],
    '/profile' => [
        'fos_user_profile_show'          => ['/',             'Profile', 'show',          ['GET']],
        'fos_user_profile_edit'          => ['/edit',         'Profile', 'edit',          ['GET', 'POST']],
        'fos_user_change_password'       => ['/change-password', 'ChangePassword', 'changePassword', ['GET', 'POST']],
    ],
];

foreach ($fosGroups as $prefix => $group) {
    foreach ($group as $id => [$path, $controller, $action, $methods]) {
        $routes[$id] = [
            'path'       => rtrim($prefix . $path, '/') ?: '/',
            'controller' => $ctrl($controller, $action),
            'methods'    => $methods,
        ];
    }
}

// ---- emit -------------------------------------------------------------------
$y  = "# GENERATED by migration/bin/port-auth-routes.php - do not edit by hand.\n";
$y .= "#\n";
$y .= "# Replaces the routes that came from FOSUserBundle's XML plus the two\n";
$y .= "# XML route files Core/UserBundle shipped. Bundle inheritance is gone in\n";
$y .= "# Symfony 4+, so every controller here points straight at the app's own\n";
$y .= "# overriding controller in App\\User\\Controller.\n\n";

foreach ($routes as $id => $r) {
    $y .= "$id:\n";
    $y .= "    path: " . $r['path'] . "\n";
    $y .= "    controller: " . $r['controller'] . "\n";
    if ($r['methods']) $y .= "    methods: [" . implode(', ', $r['methods']) . "]\n";
    $y .= "\n";
}

file_put_contents($out, $y);
printf("wrote %d auth routes -> next/config/routes/auth.yaml\n", count($routes));
foreach (array_keys($routes) as $id) echo "  $id\n";
