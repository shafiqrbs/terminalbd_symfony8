<?php

declare(strict_types=1);

/**
 * Finds routes whose controller or action does not exist, and optionally
 * removes them.
 *
 * 419 of these came across in the port. They are dead in the legacy tree too:
 * 229 name a controller class that is absent from both trees
 * (HotelReportController, EcommerceMenuController, ...) and the rest name an
 * action their controller never had. Each is a 500 in production today.
 *
 * With --prune the route is removed from the generated YAML. It runs after
 * port-routing.php in the pipeline, so re-running the whole migration
 * reproduces the same result; the catalogue keeps the record of what went.
 *
 * usage: php8.5 migration/bin/check-routes.php [--prune] [--report=path]
 */

require dirname(__DIR__, 2) . '/next/vendor/autoload.php';

use App\Kernel;
use Symfony\Component\Dotenv\Dotenv;
use Symfony\Component\Yaml\Yaml;

$root = dirname(__DIR__, 2);
$prune = in_array('--prune', $argv, true);
$report = null;

foreach ($argv as $arg) {
    if (str_starts_with($arg, '--report=')) {
        $report = substr($arg, strlen('--report='));
    }
}

(new Dotenv())->bootEnv($root . '/next/.env');

$kernel = new Kernel('dev', true);
$kernel->boot();

$router = $kernel->getContainer()->get('router');
$routes = $router->getRouteCollection();

$missingClass = [];
$missingAction = [];
$ok = 0;

foreach ($routes as $name => $route) {
    $controller = $route->getDefault('_controller');

    if (!is_string($controller) || $controller === '') {
        ++$ok;
        continue;
    }

    [$class, $method] = array_pad(explode('::', $controller, 2), 2, '__invoke');

    // Framework routes point at a service id (error_controller), not a class.
    if (!str_contains($class, '\\')) {
        ++$ok;
        continue;
    }

    if (!class_exists($class)) {
        $missingClass[$name] = [$route->getPath(), $class];
        continue;
    }

    if (!method_exists($class, $method)) {
        $missingAction[$name] = [$route->getPath(), $controller];
        continue;
    }

    ++$ok;
}

$dead = $missingClass + $missingAction;

printf("routes:            %d\n", count($routes));
printf("resolve:           %d\n", $ok);
printf("missing class:     %d\n", count($missingClass));
printf("missing action:    %d\n", count($missingAction));

// ---- catalogue -------------------------------------------------------------

if ($report !== null) {
    $out = "# Routes that cannot resolve\n\n"
        . "Generated by `migration/bin/check-routes.php`. Each names a controller class or\n"
        . "an action that exists in neither tree, so it is a 500 in the legacy application\n"
        . "today. The pipeline removes them from the generated routing with `--prune`;\n"
        . "this file is the record of what was removed, for whoever restores a controller.\n\n"
        . sprintf("- routes examined: **%d**\n- resolve to a real controller and action: **%d**\n"
            . "- controller class absent: **%d**\n- action absent: **%d**\n\n",
            count($routes), $ok, count($missingClass), count($missingAction));

    $out .= "## Controller class absent\n\n```\n";

    foreach ($missingClass as $name => [$path, $class]) {
        $out .= sprintf("%-52s %-58s %s\n", $name, $path, $class);
    }

    $out .= "```\n\n## Action absent from an existing controller\n\n```\n";

    foreach ($missingAction as $name => [$path, $controller]) {
        $out .= sprintf("%-52s %-58s %s\n", $name, $path, $controller);
    }

    $out .= "```\n";

    file_put_contents($report, $out);
    printf("wrote %s\n", $report);
}

if (!$prune || $dead === []) {
    exit(0);
}

// ---- prune -----------------------------------------------------------------

$removed = 0;

$routeFiles = glob($root . '/next/config/routes/*.yaml') ?: [];

// The 362 ported bundle files, imported by legacy.yaml, at any depth.
foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/next/config/routes/legacy')) as $candidate) {
    if (in_array($candidate->getExtension(), ['yml', 'yaml'], true)) {
        $routeFiles[] = $candidate->getPathname();
    }
}

foreach ($routeFiles as $file) {
    $parsed = Yaml::parseFile($file);

    if (!is_array($parsed)) {
        continue;
    }

    $kept = [];
    $dropped = [];

    foreach ($parsed as $name => $definition) {
        if (isset($dead[$name])) {
            $dropped[] = $name;
            continue;
        }

        $kept[$name] = $definition;
    }

    if ($dropped === []) {
        continue;
    }

    $removed += count($dropped);

    $header = [];

    foreach (file($file) as $line) {
        if (!str_starts_with($line, '#')) {
            break;
        }

        $header[] = rtrim($line, "\n");
    }

    $header[] = sprintf('# %d route(s) removed by check-routes.php: no such controller or action.', count($dropped));
    $header[] = '# See migration/contract/unresolvable-routes.md.';

    file_put_contents($file, implode("\n", $header) . "\n" . ($kept === [] ? '' : Yaml::dump($kept, 4, 4)));
}

printf("pruned:            %d route definitions\n", $removed);
