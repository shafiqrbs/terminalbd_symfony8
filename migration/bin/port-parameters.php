<?php
/**
 * Generates next/config/packages/legacy_parameters.yaml from
 * app/config/parameters.yml.dist.
 *
 * Routing and services reference container parameters such as %domain.main%.
 * Symfony 8 fails at compile time if one is missing, so the full set has to
 * exist. Values come from the .dist file (parameters.yml itself is gitignored
 * and holds real credentials), and each is wired to an environment variable so
 * deployment does not depend on a file that is not in the repository.
 *
 * Database and mailer settings are skipped - those are DATABASE_URL and
 * MAILER_DSN in .env now.
 *
 * usage: php migration/bin/port-parameters.php
 */
$root = dirname(__DIR__, 2);
$src  = "$root/app/config/parameters.yml.dist";
$out  = "$root/next/config/packages/legacy_parameters.yaml";

if (!is_file($src)) { fwrite(STDERR, "missing $src\n"); exit(1); }

$skip = [
    'database_driver', 'database_host', 'database_port', 'database_name',
    'database_user', 'database_pass', 'database_password',
    'mailer_transport', 'mailer_host', 'mailer_user', 'mailer_pass', 'mailer_password',
    'secret', 'locale',
];

$lines = file($src, FILE_IGNORE_NEW_LINES);
$params = [];
$current = null;

foreach ($lines as $l) {
    if (preg_match('/^\s{4}([A-Za-z0-9_.\-]+)\s*:\s*(.*)$/', $l, $m)) {
        $key = trim($m[1]);
        $val = trim($m[2]);
        $current = $key;
        if (in_array($key, $skip, true)) { $current = null; continue; }
        $params[$key] = $val === '' ? [] : $val;
        continue;
    }
    // list continuation ("      - Division")
    if ($current !== null && preg_match('/^\s{6,}-\s*(.+)$/', $l, $m) && is_array($params[$current] ?? null)) {
        $params[$current][] = trim($m[1]);
    }
}

$envName = static fn (string $k): string => strtoupper(str_replace(['.', '-'], '_', $k));

$y  = "# GENERATED by migration/bin/port-parameters.php from app/config/parameters.yml.dist\n";
$y .= "#\n";
$y .= "# Routing and services reference these as %name%; Symfony 8 fails to compile\n";
$y .= "# if one is missing. Each is backed by an environment variable so no\n";
$y .= "# gitignored parameters.yml is needed at deploy time. Defaults are the .dist\n";
$y .= "# placeholders - set the real values in .env.local or the environment.\n\n";
$y .= "parameters:\n";

$envLines = [];
foreach ($params as $k => $v) {
    if (is_array($v)) {
        $y .= "    '$k':\n";
        foreach ($v as $item) $y .= "        - '" . str_replace("'", "''", $item) . "'\n";
        continue;
    }
    $env = $envName($k);
    $default = ($v === '~' || $v === 'null' || $v === '') ? '' : trim($v, "'\"");
    // A null parameter is fatal where it is interpolated into a route host
    // pattern, so every parameter gets a non-empty placeholder default.
    $placeholder = $default !== '' ? $default : (str_starts_with($k, 'domain') ? 'localhost' : 'CHANGE_ME');
    $y .= "    '$k': '%env(string:$env)%'\n";
    $envLines[] = "$env=$placeholder";
}

file_put_contents($out, $y);
file_put_contents("$root/migration/contract/legacy-parameters.env", implode("\n", $envLines) . "\n");

printf("wrote %d parameters -> next/config/packages/legacy_parameters.yaml\n", count($params));
printf("env template -> migration/contract/legacy-parameters.env\n");
