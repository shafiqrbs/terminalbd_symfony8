<?php
/**
 * Generates next/config/services_legacy.yaml.
 *
 * 214 of the 358 ported form types take constructor parameters that are runtime
 * values (an entity, a repository, the current tenant's GlobalOption), not
 * services. Symfony's autowiring cannot build them, and leaving them in the
 * auto-registered App\ namespace fails container compilation outright.
 *
 * They are excluded from service registration here. That is correct for now
 * because every one of them is still instantiated with `new` at its call site -
 * exactly the sites mark-manual-forms.php flags. When a form type's
 * dependencies move into configureOptions(), delete it from this file so it
 * becomes an autowired service again.
 *
 * usage: php migration/bin/gen-service-excludes.php
 */
$root = dirname(__DIR__, 2);
$out  = "$root/next/config/services_legacy.yaml";

$excluded = [];
foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator("$root/next/src", FilesystemIterator::SKIP_DOTS)) as $f) {
    if ($f->getExtension() !== 'php') continue;
    $p = $f->getPathname();
    if (!str_contains($p, '/Form/')) continue;

    $src = (string) file_get_contents($p);
    // a constructor whose first token is not ")" - i.e. it takes parameters
    if (!preg_match('/function\s+__construct\s*\(\s*[^)\s]/', $src)) continue;

    $excluded[] = substr($p, strlen("$root/next/"));
}
sort($excluded);

$y  = "# GENERATED by migration/bin/gen-service-excludes.php - do not edit by hand.\n";
$y .= "#\n";
$y .= "# " . count($excluded) . " legacy form types take runtime values (entities, repositories,\n";
$y .= "# the tenant's GlobalOption) as constructor arguments. Autowiring cannot build\n";
$y .= "# them, so they are excluded from service registration. Each is still\n";
$y .= "# instantiated with `new` at its call site - see the TODO(migration) markers.\n";
$y .= "#\n";
$y .= "# As each form type's dependencies move into configureOptions(), remove its\n";
$y .= "# line here so it becomes an ordinary autowired service again.\n\n";
$y .= "services:\n";
$y .= "    _defaults:\n        autowire: true\n        autoconfigure: true\n\n";
$y .= "    App\\:\n";
$y .= "        resource: '../src/'\n";
$y .= "        exclude:\n";
$y .= "            - '../src/DependencyInjection/'\n";
$y .= "            - '../src/Entity/'\n";
$y .= "            - '../src/Kernel.php'\n";
$y .= "            # entity graph - data objects, never services\n";
$y .= "            - '../src/*/Entity/'\n";
$y .= "            # form types with non-autowirable constructors (see header)\n";
foreach ($excluded as $e) {
    $y .= "            - '../" . $e . "'\n";
}

file_put_contents($out, $y);
printf("wrote %d exclusions -> next/config/services_legacy.yaml\n", count($excluded));
