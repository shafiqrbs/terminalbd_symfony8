<?php
/**
 * Generates next/config/services_legacy.yaml.
 *
 * A form type whose constructor takes runtime values (an entity, a repository,
 * the current tenant's GlobalOption) cannot be autowired, and leaving it in the
 * auto-registered App\ namespace fails container compilation outright. Any such
 * type is excluded from service registration here.
 *
 * port-form-types.php moved every one of those constructors into
 * configureOptions(), so the list is expected to be empty. It stays in the
 * pipeline as a guard: if a port reintroduces one, this file catches it instead
 * of the container blowing up.
 *
 * usage: php migration/bin/gen-service-excludes.php
 */
$root = dirname(__DIR__, 2);
$out  = "$root/next/config/services_legacy.yaml";

$excluded = [];
foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator("$root/next/src", FilesystemIterator::SKIP_DOTS)) as $f) {
    if ($f->getExtension() !== 'php') continue;
    $p = $f->getPathname();
    if (!str_contains($p, '/Form/')) continue;

    $src = (string) file_get_contents($p);
    // a constructor whose first token is not ")" - i.e. it takes parameters
    if (!preg_match('/function\s+__construct\s*\(\s*[^)\s]/', $src)) continue;

    $excluded[] = substr($p, strlen("$root/next/"));
}
sort($excluded);

$y  = "# GENERATED by migration/bin/gen-service-excludes.php - do not edit by hand.\n";
$y .= "#\n";
$y .= "# " . count($excluded) . " form types take runtime values (entities, repositories, the\n";
$y .= "# tenant's GlobalOption) as constructor arguments. Autowiring cannot build them,\n";
$y .= "# so they are excluded from service registration here. port-form-types.php moves\n";
$y .= "# such constructors into configureOptions(), which is why this list should stay\n";
$y .= "# empty - a non-empty list means a port reintroduced the Symfony 2 pattern.\n";
$y .= "#\n";
$y .= "# As each form type's dependencies move into configureOptions(), remove its\n";
$y .= "# line here so it becomes an ordinary autowired service again.\n\n";
$y .= "services:\n";
$y .= "    _defaults:\n        autowire: true\n        autoconfigure: true\n\n";
$y .= "    App\\:\n";
$y .= "        resource: '../src/'\n";
$y .= "        exclude:\n";
$y .= "            - '../src/DependencyInjection/'\n";
$y .= "            - '../src/Entity/'\n";
$y .= "            - '../src/Kernel.php'\n";
$y .= "            # entity graph - data objects, never services\n";
$y .= "            - '../src/*/Entity/'\n";
$y .= "            # form types with non-autowirable constructors (see header)\n";
foreach ($excluded as $e) {
    $y .= "            - '../" . $e . "'\n";
}

file_put_contents($out, $y);
printf("wrote %d exclusions -> next/config/services_legacy.yaml\n", count($excluded));
