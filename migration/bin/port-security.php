<?php
/**
 * Ports role_hierarchy and access_control from the SF2.8 app/config/security.yml
 * into next/config/packages/security.yaml.
 *
 * 193 role-hierarchy entries and 44 access-control rules is too much to copy by
 * hand, and a single dropped role silently opens or closes a module for a whole
 * tenant. Generated instead, and regenerated if the legacy file changes.
 *
 * Firewalls are NOT ported: SF2's ajax_form_login/anonymous have no SF8
 * equivalent and are hand-written in the target file.
 *
 * usage: php migration/bin/port-security.php
 */
$root = dirname(__DIR__, 2);
$src  = "$root/app/config/security.yml";
$out  = "$root/next/config/packages/security_roles.yaml";

$lines = file($src, FILE_IGNORE_NEW_LINES);

$hierarchy = [];
$selfOnly  = [];
$access    = [];
$section   = null;

foreach ($lines as $l) {
    if (preg_match('/^\s{4}(role_hierarchy|providers|firewalls|access_control):/', $l, $m)) {
        $section = $m[1];
        continue;
    }
    if (preg_match('/^\s{0,4}\S/', $l) && !preg_match('/^\s{4}\S/', $l)) {
        // top-level key such as "security:" - keep current section
    }

    if ($section === 'role_hierarchy'
        && preg_match('/^\s+(ROLE_[A-Z0-9_]+):\s*\[([^\]]*)\]/', $l, $m)) {
        $roles = array_values(array_filter(array_map('trim', explode(',', $m[2]))));
        // A role inheriting itself is a no-op in SF2 and an error to reason about; drop it.
        $roles = array_values(array_filter($roles, static fn (string $r): bool => $r !== $m[1]));
        if ($roles) {
            $hierarchy[$m[1]] = array_values(array_unique(
                array_merge($hierarchy[$m[1]] ?? [], $roles)
            ));
        } else {
            // "ROLE_X: [ROLE_X]" - a role inheriting only itself. Symfony grants a
            // role to whoever holds it whether or not it appears in the hierarchy,
            // so these are no-ops. Kept as a comment: the names are the app's
            // permission vocabulary and dropping them silently would hide them.
            $selfOnly[$m[1]] = true;
        }
        continue;
    }

    if ($section === 'access_control'
        && preg_match('/^\s+-\s*\{\s*path:\s*([^,]+?)\s*,\s*role:\s*([A-Z_]+)\s*\}/', $l, $m)) {
        $access[] = ['path' => trim($m[1]), 'role' => $m[2]];
    }
}

// SF8 renamed the anonymous marker.
$roleMap = ['IS_AUTHENTICATED_ANONYMOUSLY' => 'PUBLIC_ACCESS'];

$y  = "# GENERATED by migration/bin/port-security.php from app/config/security.yml\n";
$y .= "# Do not edit by hand - re-run the script instead.\n";
$y .= "#\n";
$y .= "# " . count($hierarchy) . " role_hierarchy entries, " . count($access) . " access_control rules.\n";
$y .= "security:\n    role_hierarchy:\n";

$width = max(array_map('strlen', array_keys($hierarchy)));
foreach ($hierarchy as $role => $inherits) {
    $y .= sprintf("        %-{$width}s [%s]\n", $role . ':', implode(', ', $inherits));
}

if ($selfOnly) {
    $names = array_keys($selfOnly);
    sort($names);
    $y .= "\n#\n# Declared in the legacy file as \"ROLE_X: [ROLE_X]\" - a role inheriting only\n";
    $y .= "# itself, which Symfony treats as a no-op. Listed here so the permission\n";
    $y .= "# vocabulary stays visible; they are granted directly, not by hierarchy.\n#\n";
    foreach (array_chunk($names, 2) as $pair) {
        $y .= '#   ' . implode('  ', array_map(static fn (string $n): string => sprintf('%-46s', $n), $pair)) . "\n";
    }
}

$y .= "\n    access_control:\n";
foreach ($access as $rule) {
    $role = $roleMap[$rule['role']] ?? $rule['role'];
    $y .= sprintf("        - { path: %-24s roles: %s }\n", "'" . $rule['path'] . "',", $role);
}

file_put_contents($out, $y);
printf("wrote %s\n  %d role_hierarchy entries\n  %d access_control rules\n",
    str_replace("$root/", '', $out), count($hierarchy), count($access));

printf("  %d self-only roles recorded as comments\n", count($selfOnly));
