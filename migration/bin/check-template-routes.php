<?php

declare(strict_types=1);

/**
 * Finds path()/url() calls in templates naming a route that does not exist.
 *
 * Twig's linter parses templates but resolves nothing, so a link to a route
 * that was never defined only shows up when the page is rendered - and then it
 * takes down the whole page, not just the link. 200 route names are referenced
 * this way; none of them is defined in the legacy tree either, so those pages
 * are 500s in production today.
 *
 * Reports, does not gate: fixing them means deciding per link whether to
 * restore a controller or delete the link, which is a product decision.
 *
 * usage: php8.5 migration/bin/check-template-routes.php [--report=path]
 */

require dirname(__DIR__, 2) . '/next/vendor/autoload.php';

use App\Kernel;
use Symfony\Component\Dotenv\Dotenv;

$root = dirname(__DIR__, 2);
$report = null;

foreach ($argv as $arg) {
    if (str_starts_with($arg, '--report=')) {
        $report = substr($arg, strlen('--report='));
    }
}

(new Dotenv())->bootEnv($root . '/next/.env');

$kernel = new Kernel('dev', true);
$kernel->boot();

$known = [];

foreach ($kernel->getContainer()->get('router')->getRouteCollection() as $name => $route) {
    $known[$name] = true;
}

$missing = [];
$references = 0;

foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/next/templates')) as $file) {
    if ($file->getExtension() !== 'twig') {
        continue;
    }

    $code = file_get_contents($file->getPathname());

    if (!preg_match_all('/(?:path|url)\(\s*[\'"]([a-zA-Z0-9_]+)[\'"]/', $code, $matches)) {
        continue;
    }

    foreach ($matches[1] as $name) {
        if (isset($known[$name])) {
            continue;
        }

        ++$references;
        $missing[$name][] = substr($file->getPathname(), strlen($root . '/next/'));
    }
}

ksort($missing);

printf("template links to routes that do not exist: %d names, %d references\n", count($missing), $references);

if ($report !== null) {
    $out = "# Template links to routes that do not exist\n\n"
        . "Generated by `migration/bin/check-template-routes.php`.\n\n"
        . "`path('x')` for an undefined route throws while rendering, so one dead link takes down\n"
        . "the whole page. None of these names is defined in the legacy tree either - the pages\n"
        . "carrying them are 500s in production today. Fixing one means deciding whether to\n"
        . "restore its controller or remove the link, which is a product decision, so this file\n"
        . "reports rather than gates.\n\n"
        . sprintf("- route names: **%d**\n- references: **%d**\n\n```\n", count($missing), $references);

    foreach ($missing as $name => $files) {
        $out .= sprintf("%-38s %d reference(s)  e.g. %s\n", $name, count($files), $files[0]);
    }

    $out .= "```\n";
    file_put_contents($report, $out);
    printf("wrote %s\n", $report);
}
