<?php

declare(strict_types=1);

/**
 * Compares the ported Doctrine mapping against a real database dump.
 *
 * Answers the questions §11 of the plan could not: does every entity's table
 * exist, does every mapped column exist in it, and are the 24 serialized
 * `array` columns really holding serialize() output?
 *
 * No database connection is needed - the dump is parsed directly, so this runs
 * anywhere the dump does.
 *
 * usage: php8.5 migration/bin/schema-diff.php <dump.sql.gz|dump.sql> [--report=path]
 */

require dirname(__DIR__, 2) . '/next/vendor/autoload.php';

use App\Kernel;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\ORM\Mapping\ClassMetadata;
use Symfony\Component\Dotenv\Dotenv;

$root = dirname(__DIR__, 2);
$dump = $argv[1] ?? $root . '/bm_db.sql.gz';
$report = null;

foreach ($argv as $arg) {
    if (str_starts_with($arg, '--report=')) {
        $report = substr($arg, strlen('--report='));
    }
}

if (!is_file($dump)) {
    fwrite(STDERR, "no such dump: {$dump}\n");
    exit(2);
}

// ---- 1. read the dump ------------------------------------------------------

$handle = str_ends_with($dump, '.gz') ? gzopen($dump, 'rb') : fopen($dump, 'rb');
$read = str_ends_with($dump, '.gz') ? 'gzgets' : 'fgets';

$tables = [];
$serialized = [];
$current = null;

while (($line = $read($handle)) !== false) {
    $trimmed = trim($line);

    if (preg_match('/^CREATE TABLE [`"]?([\w$]+)[`"]?/i', $trimmed, $m)) {
        $current = $m[1];
        $tables[$current] = [];
        continue;
    }

    if ($current !== null) {
        if (str_starts_with($trimmed, ')')) {
            $current = null;
            continue;
        }

        if (preg_match('/^[`"]([\w$]+)[`"]\s+([a-z]+)/i', $trimmed, $m)) {
            $tables[$current][$m[1]] = strtolower($m[2]);
        }

        continue;
    }

    // Sample the first INSERT for each table so the serialized columns can be
    // checked against real values.
    if (preg_match('/^INSERT INTO [`"]?([\w$]+)[`"]?\s*\(([^)]*)\)\s*VALUES/i', $trimmed, $m)) {
        $table = $m[1];

        if (!isset($serialized[$table]) && preg_match_all("/'((?:a|O):\d+:\{.*?)'\s*[,)]/", $line, $vm)) {
            $serialized[$table] = $vm[1][0];
        }
    }
}

printf("dump: %s\n%d tables\n\n", basename($dump), count($tables));

// ---- 2. read the mapping ---------------------------------------------------

(new Dotenv())->bootEnv($root . '/next/.env');

$kernel = new Kernel('dev', true);
$kernel->boot();

/** @var EntityManagerInterface $em */
$em = $kernel->getContainer()->get('doctrine')->getManager();
$all = $em->getMetadataFactory()->getAllMetadata();

$missingTables = [];
$missingColumns = [];
$extraColumns = [];
$arrayColumns = [];
$checked = 0;

foreach ($all as $meta) {
    /** @var ClassMetadata $meta */
    if ($meta->isMappedSuperclass) {
        continue;
    }

    $table = $meta->getTableName();

    if (!isset($tables[$table])) {
        $missingTables[] = sprintf('%-52s %s', $meta->getName(), $table);
        continue;
    }

    ++$checked;
    $mapped = [];

    foreach ($meta->fieldMappings as $field => $mapping) {
        $column = $mapping->columnName ?? $mapping['columnName'] ?? $field;
        $mapped[$column] = true;
        $type = $mapping->type ?? $mapping['type'] ?? '';

        if (in_array($type, ['array', 'json_array', 'object'], true)) {
            $arrayColumns[] = [$meta->getName(), $table, $column, $type];
        }

        if (!isset($tables[$table][$column])) {
            $missingColumns[] = sprintf('%-52s %s.%s', $meta->getName(), $table, $column);
        }
    }

    foreach ($meta->associationMappings as $field => $mapping) {
        foreach ($mapping->joinColumns ?? $mapping['joinColumns'] ?? [] as $joinColumn) {
            $column = $joinColumn->name ?? $joinColumn['name'];
            $mapped[$column] = true;

            if (!isset($tables[$table][$column])) {
                $missingColumns[] = sprintf('%-52s %s.%s (join column for %s)', $meta->getName(), $table, $column, $field);
            }
        }
    }

    foreach (array_keys($tables[$table]) as $column) {
        if (!isset($mapped[$column])) {
            $extraColumns[] = sprintf('%-52s %s.%s', $meta->getName(), $table, $column);
        }
    }
}

// ---- 3. report -------------------------------------------------------------

$out = [];
$out[] = '# Schema diff: ported mapping vs ' . basename($dump);
$out[] = '';
$out[] = sprintf('Generated by `migration/bin/schema-diff.php`. %d entity metadata definitions, ', count($all))
    . sprintf('%d matched against a table in the dump.', $checked);
$out[] = '';
$out[] = sprintf('| | count |');
$out[] = '|---|---:|';
$out[] = sprintf('| tables in the dump | %d |', count($tables));
$out[] = sprintf('| entities whose table is absent from the dump | %d |', count($missingTables));
$out[] = sprintf('| mapped columns absent from their table | %d |', count($missingColumns));
$out[] = sprintf('| table columns absent from the mapping | %d |', count($extraColumns));
$out[] = sprintf('| columns mapped as a serialized PHP type | %d |', count($arrayColumns));
$out[] = '';

$section = static function (string $title, array $lines, string $note = '') use (&$out): void {
    $out[] = '## ' . $title . ' (' . count($lines) . ')';
    $out[] = '';

    if ($note !== '') {
        $out[] = $note;
        $out[] = '';
    }

    if ($lines === []) {
        $out[] = '_none_';
        $out[] = '';

        return;
    }

    $out[] = '```';

    foreach ($lines as $line) {
        $out[] = $line;
    }

    $out[] = '```';
    $out[] = '';
};

$section(
    'Mapped columns missing from the database',
    $missingColumns,
    'These would fail on the first query touching the entity. Anything here is a port defect.',
);
$section(
    'Entity tables not present in this dump',
    $missingTables,
    'The dump is one tenant database; a table missing here is not proof the table is missing in production.',
);

$arrayLines = [];

foreach ($arrayColumns as [$class, $table, $column, $type]) {
    $sample = $serialized[$table] ?? null;
    $arrayLines[] = sprintf('%-52s %s.%s (%s)%s', $class, $table, $column, $type, $sample !== null ? '  [serialize() output seen in dump]' : '');
}

$section(
    'Columns still holding serialized PHP',
    $arrayLines,
    'LegacyArrayType reproduces DBAL 3 semantics for these. See §7 of the plan: converting them to json needs its own backfill.',
);
$section(
    'Columns in the database with no mapping',
    array_slice($extraColumns, 0, 200),
    'Usually legacy columns the entity stopped using. Harmless to read, but a NOT NULL one without a default breaks inserts.',
);

$text = implode("\n", $out) . "\n";

if ($report !== null) {
    file_put_contents($report, $text);
    printf("wrote %s\n", $report);
}

printf("entities checked:                 %d\n", $checked);
printf("mapped columns missing from DB:   %d\n", count($missingColumns));
printf("entity tables not in this dump:   %d\n", count($missingTables));
printf("db columns not in the mapping:    %d\n", count($extraColumns));
printf("serialized columns:               %d\n", count($arrayColumns));

exit(count($missingColumns) > 0 ? 1 : 0);
