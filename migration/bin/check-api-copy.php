<?php

declare(strict_types=1);

/**
 * Does terminalbd_api's copy still agree with what the legacy tree implies?
 *
 * The API has its own copy of the 874 non-presentation files (§3 of
 * API-REACT-PLAN.md), so an entity change there is an ordinary edit. But the
 * pipeline that produced them is still the only thing that reads the legacy
 * tree, and four of the guards in ci-checks.sh depend on that reading. So the
 * pipeline keeps running - into a scratch directory - and its output is compared
 * against the copy. Nothing is written to the copy; this only answers whether
 * the two still agree.
 *
 * Three ways they can disagree, and only the third is ever expected:
 *
 * 1. A non-presentation file the API does not have. The copy missed it, or the
 *    legacy tree grew one.
 * 2. A file the API has that the pipeline does not produce, outside its own
 *    Api\ namespace.
 * 3. A file whose content differs. Some of those are deliberate - the API drops
 *    Twig, and ORM 3.7 forced an inverse-side fix - so each is recorded with its
 *    reason in migration/api-copy-differences.txt. An unrecorded difference
 *    fails, and so does a recorded one that has stopped differing: a baseline
 *    nobody prunes stops being a baseline.
 *
 * usage: php8.5 migration/bin/check-api-copy.php [--source=next/src]
 *                                                [--api=../terminalbd_api/src]
 *                                                [--update-baseline]
 */

$root = dirname(__DIR__, 2);
$source = $root . '/next/src';
$api = dirname($root) . '/terminalbd_api/src';
$baselineFile = $root . '/migration/api-copy-differences.txt';
$update = false;

foreach (array_slice($argv, 1) as $arg) {
    if (str_starts_with($arg, '--source=')) {
        $source = substr($arg, 9);
    } elseif (str_starts_with($arg, '--api=')) {
        $api = substr($arg, 6);
    } elseif ($arg === '--update-baseline') {
        $update = true;
    } else {
        fwrite(STDERR, "unknown option: {$arg}\n");

        exit(2);
    }
}

if (!is_dir($source) || !is_dir($api)) {
    fwrite(STDERR, "not a directory: " . (is_dir($source) ? $api : $source) . "\n");

    exit(2);
}

/**
 * What React replaces, and what the API therefore does not carry.
 *
 * Derived from the copy itself rather than guessed: of the 704 files next/src
 * has and the API does not, 337 are controllers, 360 are form types, 6 are Twig
 * extensions and one is Form/ChoiceList.php.
 */
function isPresentation(string $path): bool
{
    return str_contains($path, '/Controller/')
        || str_ends_with($path, 'Controller.php')
        || str_starts_with($path, 'Form/')
        || str_contains($path, '/Form/')
        || str_contains($path, 'Twig');
}

function phpFiles(string $root): array
{
    $out = [];
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS));

    foreach ($it as $file) {
        if ($file->isFile() && $file->getExtension() === 'php') {
            $out[] = substr($file->getPathname(), strlen($root) + 1);
        }
    }

    sort($out);

    return $out;
}

$baseline = [];

if (is_file($baselineFile)) {
    foreach (file($baselineFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
        if (str_starts_with($line, '#')) {
            continue;
        }

        [$path, $reason] = array_pad(explode("\t", $line, 2), 2, '');
        $baseline[$path] = $reason;
    }
}

$sourceFiles = phpFiles($source);
$apiFiles = array_flip(phpFiles($api));

$missing = [];
$differing = [];

foreach ($sourceFiles as $path) {
    if (isPresentation($path)) {
        continue;
    }

    if (!isset($apiFiles[$path])) {
        $missing[] = $path;

        continue;
    }

    if (file_get_contents($source . '/' . $path) !== file_get_contents($api . '/' . $path)) {
        $differing[] = $path;
    }
}

$sourceSet = array_flip($sourceFiles);
$extra = [];

foreach (array_keys($apiFiles) as $path) {
    if (!isset($sourceSet[$path]) && !str_starts_with($path, 'Api/')) {
        $extra[] = $path;
    }
}

if ($update) {
    $lines = [
        "# Files where terminalbd_api's copy deliberately differs from what the pipeline",
        "# produces. Generated by check-api-copy.php --update-baseline; the reasons are",
        "# written by hand, and a line without one is not a baseline, it is a shrug.",
        '#',
        "# An entry that has stopped differing fails the check. Prune it.",
        '',
    ];

    foreach ($differing as $path) {
        $reason = $baseline[$path] ?? 'REVIEW - no reason recorded';
        $lines[] = $path . "\t" . $reason;
    }

    file_put_contents($baselineFile, implode("\n", $lines) . "\n");
    printf("wrote %s - %d entries\n", $baselineFile, count($differing));

    exit(0);
}

$unrecorded = array_values(array_filter($differing, static fn (string $p): bool => !isset($baseline[$p])));
$stale = array_values(array_diff(array_keys($baseline), $differing));
$unreasoned = array_values(array_filter(
    $differing,
    static fn (string $p): bool => str_starts_with($baseline[$p] ?? '', 'REVIEW')
));

printf(
    "api copy: %d source files, %d non-presentation, %d differ (%d recorded)\n",
    count($sourceFiles),
    count($sourceFiles) - count(array_filter($sourceFiles, 'isPresentation')),
    count($differing),
    count($differing) - count($unrecorded)
);

$failed = false;

foreach ([
    ['not copied into the API', $missing],
    ['in the API but not produced by the pipeline', $extra],
    ['differ with no recorded reason', $unrecorded],
    ['recorded as differing but identical now - prune them', $stale],
    ['recorded with REVIEW instead of a reason', $unreasoned],
] as [$label, $list]) {
    if ($list === []) {
        continue;
    }

    $failed = true;
    printf("\n  %d %s:\n", count($list), $label);

    foreach (array_slice($list, 0, 20) as $path) {
        printf("    %s\n", $path);
    }

    if (count($list) > 20) {
        printf("    ... and %d more\n", count($list) - 20);
    }
}

if ($failed) {
    fwrite(STDERR, "\nFAIL: the API copy and the pipeline disagree.\n");

    exit(1);
}

printf("PASS: every difference is recorded.\n");
