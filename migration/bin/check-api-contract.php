<?php

declare(strict_types=1);

/**
 * Guards the 96 mobile endpoints.
 *
 * The Android and Flutter clients cannot be updated in lockstep with the
 * server, so their URLs are locked. This compares the router against
 * migration/contract/api-endpoints.json, extracted from the legacy tree, and
 * fails if an endpoint that used to resolve stops resolving.
 *
 * Endpoints that are already dead in the legacy application are listed in
 * migration/contract/dead-mobile-endpoints.md and accepted here; the exit code
 * is about regressions, not about the defects the port inherited.
 *
 * usage: php8.5 migration/bin/check-api-contract.php [--report=path]
 */

require dirname(__DIR__, 2) . '/next/vendor/autoload.php';

use App\Kernel;
use Symfony\Component\Dotenv\Dotenv;

$root = dirname(__DIR__, 2);
$report = null;

foreach ($argv as $arg) {
    if (str_starts_with($arg, '--report=')) {
        $report = substr($arg, strlen('--report='));
    }
}

$contract = json_decode((string) file_get_contents($root . '/migration/contract/api-endpoints.json'), true);

/** Endpoints with no implementation in either tree - see the catalogue. */
const KNOWN_DEAD = [
    'api_system_purchase_item',
    'api_system_sales_item',
    'api_portal_app_user_register',
    'api_poskeeper_instant_purchase',
    'api_poskeeper_sales_update',
    'api_portal_app',
];

(new Dotenv())->bootEnv($root . '/next/.env');

$kernel = new Kernel('dev', true);
$kernel->boot();

$routes = $kernel->getContainer()->get('router')->getRouteCollection();

$live = [];
$dead = [];
$regressions = [];

foreach ($contract as $endpoint) {
    $route = $routes->get($endpoint['name']);

    if ($route === null) {
        if (in_array($endpoint['name'], KNOWN_DEAD, true)) {
            $dead[] = $endpoint;
            continue;
        }

        $regressions[] = $endpoint;
        continue;
    }

    if ($route->getPath() !== $endpoint['url']) {
        // A duplicate route name: Symfony kept the last definition, as
        // Symfony 2 did, so this URL is unreachable in both applications.
        if (in_array($endpoint['name'], KNOWN_DEAD, true)) {
            $dead[] = $endpoint + ['now' => $route->getPath()];
            continue;
        }

        $regressions[] = $endpoint + ['now' => $route->getPath()];
        continue;
    }

    $live[] = $endpoint;
}

printf("mobile endpoints in the contract: %d\n", count($contract));
printf("resolving, at the same path:      %d\n", count($live));
printf("known dead (see catalogue):       %d\n", count($dead));
printf("regressions:                      %d\n", count($regressions));

foreach ($regressions as $endpoint) {
    printf("  REGRESSION %-38s %s%s\n", $endpoint['name'], $endpoint['url'],
        isset($endpoint['now']) ? ' (now ' . $endpoint['now'] . ')' : ' (route absent)');
}

if ($report !== null) {
    $out = "# Mobile API contract\n\n"
        . "Generated by `migration/bin/check-api-contract.php`.\n\n"
        . sprintf("- endpoints in the contract: **%d**\n- resolving at the same path: **%d**\n"
            . "- dead in the legacy application too: **%d**\n- regressions: **%d**\n\n",
            count($contract), count($live), count($dead), count($regressions));

    $out .= "## Live\n\n```\n";

    foreach ($live as $endpoint) {
        $out .= sprintf("%-40s %s\n", $endpoint['name'], $endpoint['url']);
    }

    $out .= "```\n";

    file_put_contents($report, $out);
    printf("wrote %s\n", $report);
}

exit($regressions === [] ? 0 : 1);
