<?php

declare(strict_types=1);

/**
 * Rolls the two sweeps up per module, which is the unit phase 5 flips.
 *
 * §8 moves the proxy one module at a time, so "the smoke test passes" is the
 * wrong granularity to decide on: it hides that a module is green because it
 * was thoroughly exercised, or green because this tenant has no rows for it and
 * almost nothing ran. Both look like a high pass rate. The column that matters
 * is how much of the module the sweeps could actually reach.
 *
 * Reads the harnesses' own state files rather than re-running them, so it is
 * cheap and always reflects the last full sweep.
 *
 * usage: php8.5 migration/bin/module-summary.php [--report=path]
 */

require dirname(__DIR__, 2) . '/next/vendor/autoload.php';

use App\Kernel;
use Symfony\Component\Dotenv\Dotenv;

$root = dirname(__DIR__, 2);
$report = null;

foreach ($argv as $arg) {
    if (str_starts_with($arg, '--report=')) {
        $report = substr($arg, strlen('--report='));
    }
}

(new Dotenv())->bootEnv($root . '/next/.env');

$kernel = new Kernel('dev', true);
$kernel->boot();

/** route name -> module, from the controller the route resolves to. */
$moduleOf = [];
$routeTotal = [];

foreach ($kernel->getContainer()->get('router')->getRouteCollection() as $name => $route) {
    $controller = (string) $route->getDefault('_controller');

    if (!preg_match('/^App\\\\([A-Za-z]+)\\\\Controller\\\\/', $controller, $m)) {
        continue;
    }

    $moduleOf[$name] = $m[1];
    $routeTotal[$m[1]] = ($routeTotal[$m[1]] ?? 0) + 1;
}

$smoke = json_decode((string) @file_get_contents($root . '/next/var/smoke-state.json'), true) ?: [];
$write = json_decode((string) @file_get_contents($root . '/next/var/write-state.json'), true) ?: [];

$stats = [];

foreach ($smoke['seen'] ?? [] as $name => $status) {
    $module = $moduleOf[$name] ?? null;

    if ($module === null) {
        continue;
    }

    $stats[$module]['visited'] = ($stats[$module]['visited'] ?? 0) + 1;
    $key = $status === '200' ? 'ok' : ($status === '5xx' ? 'failed' : 'other');
    $stats[$module][$key] = ($stats[$module][$key] ?? 0) + 1;
}

// Write-test keys look like "route_name#0 -> /the/path".
foreach ($write['seen'] ?? [] as $key => $outcome) {
    $name = strtok($key, '#');
    $module = $moduleOf[$name] ?? null;

    if ($module === null) {
        continue;
    }

    $stats[$module]['forms'] = ($stats[$module]['forms'] ?? 0) + 1;

    if ($outcome === 'saved') {
        $stats[$module]['saved'] = ($stats[$module]['saved'] ?? 0) + 1;
    }
}

ksort($stats);

$rows = [];
$totals = ['routes' => 0, 'visited' => 0, 'ok' => 0, 'failed' => 0, 'forms' => 0, 'saved' => 0];

foreach ($stats as $module => $s) {
    $routes = $routeTotal[$module] ?? 0;
    $visited = $s['visited'] ?? 0;
    $ok = $s['ok'] ?? 0;
    $failed = $s['failed'] ?? 0;
    $forms = $s['forms'] ?? 0;
    $saved = $s['saved'] ?? 0;

    $rows[] = [$module, $routes, $visited, $ok, $failed, $forms, $saved,
        $visited > 0 ? (int) round(100 * $ok / $visited) : 0,
        $routes > 0 ? (int) round(100 * $visited / $routes) : 0];

    $totals['routes'] += $routes;
    $totals['visited'] += $visited;
    $totals['ok'] += $ok;
    $totals['failed'] += $failed;
    $totals['forms'] += $forms;
    $totals['saved'] += $saved;
}

printf("%-18s %7s %7s %5s %6s %6s %6s %5s %6s\n", 'module', 'routes', 'visited', 'ok', 'failed', 'forms', 'saved', 'ok%', 'reach%');

foreach ($rows as $r) {
    printf("%-18s %7d %7d %5d %6d %6d %6d %4d%% %5d%%\n", ...$r);
}

printf(
    "%-18s %7d %7d %5d %6d %6d %6d\n",
    'TOTAL',
    $totals['routes'],
    $totals['visited'],
    $totals['ok'],
    $totals['failed'],
    $totals['forms'],
    $totals['saved']
);

if ($report !== null) {
    $out = "# Per-module verification\n\n"
        . "Generated by `migration/bin/module-summary.php` from the two sweeps' state files.\n\n"
        . "§8 flips the proxy one module at a time, so this is the granularity the decision is\n"
        . "actually made at. **`reach%` is the column to read first**: a module can show a high\n"
        . "`ok%` because it was exercised and works, or because this tenant has no rows for it\n"
        . "and the sweep never got past the first page. Only the first kind is evidence.\n\n"
        . "`routes` counts every route resolving to that module's controllers, including POST-only\n"
        . "and placeholder routes the smoke sweep deliberately does not visit, so `reach%` is a\n"
        . "floor rather than a coverage figure.\n\n"
        . "| module | routes | visited | 200 | 5xx | forms | saved | ok% | reach% |\n"
        . "|---|---:|---:|---:|---:|---:|---:|---:|---:|\n";

    foreach ($rows as [$module, $routes, $visited, $ok, $failed, $forms, $saved, $okPct, $reachPct]) {
        $out .= sprintf(
            "| %s | %d | %d | %d | %d | %d | %d | %d%% | %d%% |\n",
            $module, $routes, $visited, $ok, $failed, $forms, $saved, $okPct, $reachPct
        );
    }

    $out .= sprintf(
        "| **total** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** | | |\n",
        $totals['routes'], $totals['visited'], $totals['ok'], $totals['failed'], $totals['forms'], $totals['saved']
    );

    file_put_contents($report, $out);
    printf("\nwrote %s\n", $report);
}
