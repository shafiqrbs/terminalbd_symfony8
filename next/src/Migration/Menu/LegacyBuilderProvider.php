<?php

declare(strict_types=1);

namespace App\Migration\Menu;

use Knp\Menu\FactoryInterface;
use Knp\Menu\ItemInterface;
use Knp\Menu\Provider\MenuProviderInterface;
use Psr\Container\ContainerInterface;

/**
 * Calls the ported menu builders the way KnpMenuBundle 2 called them.
 *
 * Version 2 resolved 'Appearance/Builder/mainMenu' through its
 * BundleMenuProvider, which invoked
 *
 *     $builder->mainMenu($factory, $options)
 *
 * Version 3 dropped that provider. Its replacement, the knp_menu.menu_builder
 * tag, invokes `$builder->mainMenu($options)` instead - the factory is gone
 * from the signature, because a builder registered as a service is expected to
 * have been given one.
 *
 * The ported builders still carry the two-argument signature, and rewriting
 * them is not a fair trade: App\Appearance\Menu\Builder alone is 2,100 lines
 * whose every method threads $factory through, and it is regenerated from the
 * legacy tree on each pipeline run. This provider supplies the factory instead,
 * so the builders stay byte-for-byte what the legacy application had.
 *
 * The alias map is generated by migration/bin/port-knp-menus.php, which writes
 * the same aliases into the templates.
 */
final class LegacyBuilderProvider implements MenuProviderInterface
{
    /**
     * @param array<string, array{0: string, 1: string}> $map alias => [service id, method]
     */
    public function __construct(
        private readonly FactoryInterface $factory,
        private readonly ContainerInterface $builders,
        private readonly array $map,
    ) {
    }

    public function get(string $name, array $options = []): ItemInterface
    {
        if (!isset($this->map[$name])) {
            throw new \InvalidArgumentException(sprintf('The menu "%s" is not defined.', $name));
        }

        [$id, $method] = $this->map[$name];

        return $this->builders->get($id)->{$method}($this->factory, $options);
    }

    public function has(string $name, array $options = []): bool
    {
        return isset($this->map[$name]);
    }
}
